// Bakes every sprite/tileset into public/assets. Run: npm run art
import { writePNG, sheet, scale, Grid } from './pix.mjs';
import { CAST, characterFrames, portrait } from './art/characters.mjs';
import { TILES, tileset } from './art/tiles.mjs';
import * as P from './art/props.mjs';
import { MAPS, LEGEND } from '../src/data/map.ts';

const A = 'public/assets/', PV = 'tools/preview/';

// characters
const sheets = {};
for (const [name, c] of Object.entries(CAST)) {
  sheets[name] = sheet(characterFrames(c));
  writePNG(`${A}${name}.png`, sheets[name]);
  writePNG(`${A}${name}_face.png`, portrait(c));
}
const all = new Grid(16 * 9, 24 * Object.keys(sheets).length);
Object.values(sheets).forEach((p, i) => all.blit(p, 0, i * 24));
writePNG(`${PV}characters.png`, scale(all, 5), [96, 110, 90, 255]);

// tiles + props
const ts = tileset();
writePNG(`${A}tiles.png`, ts);
writePNG(`${PV}tiles.png`, scale(ts, 4), [255, 0, 255, 255]);
const props = {
  court: P.court(), goalL: P.goal(false), goalR: P.goal(true), tree1: P.tree(3), tree2: P.tree(8), swings: P.swings(), car: P.car(),
  soul: P.soul(), chalk: P.chalk(), stickH: P.stickH(), cloud: P.cloud(), sparkle: P.sparkle(), sandwich: P.sandwich(), key: P.key(), flag: P.flag(),
  chain: P.chain(), flask: P.flask(), flaskLiquid: P.flaskLiquid(), beaker: P.beaker(), beakerLiquid: P.beakerLiquid(),
  tractor: P.tractor(), tractorRide: P.tractorRide(sheets), ball: P.ball(), arrow: P.arrow(),
  swingRed: P.swingRed(), slide: P.slide(), pullup: P.pullup(),
};
for (const [n, g] of Object.entries(props)) writePNG(`${A}${n}.png`, g);

// map previews (tiles + props + NPC markers) so layouts can be eyeballed without running the game
const idx = Object.fromEntries(TILES.map(([n], i) => [n, i]));
const tileGrid = (i) => { const g = new Grid(16, 16); for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) g.px[y * 16 + x] = ts.get((i % 16) * 16 + x, Math.floor(i / 16) * 16 + y); return g; };
for (const [id, def] of Object.entries(MAPS)) {
  const map = new Grid(def.rows[0].length * 16, def.rows.length * 16);
  def.rows.forEach((row, y) => [...row].forEach((ch, x) => map.blit(tileGrid(idx[LEGEND[ch]] ?? 0), x * 16, y * 16)));
  for (const p of def.props) if (props[p.key]) map.blit(props[p.key], p.x, p.y);
  writePNG(`${PV}map-${id}.png`, map);
}
console.log('baked', Object.keys(sheets).length, 'characters,', TILES.length, 'tiles,', Object.keys(props).length, 'props');

// tile index list for the game (generated — do not edit by hand)
import { writeFileSync } from 'node:fs';
writeFileSync('src/data/tiles.gen.ts', `// Generated by tools/bake-art.mjs — tile name -> index in public/assets/tiles.png\nexport const TILE_NAMES = ${JSON.stringify(TILES.map(([n]) => n))} as const;\n`);
// asset manifest so BootScene loads exactly what was baked (generated — do not edit by hand)
writeFileSync('src/data/assets.gen.ts', `// Generated by tools/bake-art.mjs\nexport const PEOPLE = ${JSON.stringify(Object.keys(sheets))} as const;\nexport const PROPS = ${JSON.stringify(Object.keys(props))} as const;\n`);
// props preview sheet (x3) for eyeballing
{
  const list = Object.values(props).filter(g => g.w <= 80);
  const W = list.reduce((a, g) => a + g.w + 4, 0), H = Math.max(...list.map(g => g.h));
  const sheetG = new Grid(W, H); let x = 0;
  for (const g of list) { sheetG.blit(g, x, H - g.h); x += g.w + 4; }
  writePNG(`${PV}props.png`, scale(sheetG, 3), [96, 110, 90, 255]);
}
